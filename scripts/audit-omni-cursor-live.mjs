import { spawn } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

const helperPath = process.argv[2]
const interactiveBundleIdentifiers = new Set([
  'com.apple.finder',
  'com.apple.Safari',
  'com.google.Chrome',
  'com.apple.mail',
  'com.apple.iCal',
  'com.apple.Notes',
  'com.apple.Terminal',
  'com.apple.dt.Xcode',
  'com.apple.iphonesimulator',
  'com.apple.Preview',
  'com.apple.TextEdit'
])

if (!helperPath) {
  throw new Error('Usage: node scripts/audit-omni-cursor-live.mjs <packaged-helper-path>')
}

const wait = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds))

async function runProcess(executable, args, timeoutMs = 10_000) {
  return await new Promise((resolve, reject) => {
    const child = spawn(executable, args, { shell: false, stdio: ['ignore', 'pipe', 'pipe'] })
    let stdout = ''
    let stderr = ''
    const timer = setTimeout(() => {
      child.kill('SIGTERM')
      reject(new Error(`${path.basename(executable)} timed out.`))
    }, timeoutMs)
    child.stdout.on('data', (chunk) => { stdout += String(chunk) })
    child.stderr.on('data', (chunk) => { stderr += String(chunk) })
    child.once('error', reject)
    child.once('close', (code) => {
      clearTimeout(timer)
      if (code === 0) resolve({ stdout, stderr })
      else reject(new Error(`${path.basename(executable)} exited with code ${code}; ${stderr.trim() || 'no diagnostic output'}`))
    })
  })
}

async function helper(command, timeoutMs = 10_000) {
  const id = randomUUID()
  const request = JSON.stringify({ version: 1, id, ...command })
  return await new Promise((resolve, reject) => {
    const child = spawn(helperPath, [], { shell: false, stdio: ['pipe', 'pipe', 'pipe'] })
    let stdout = ''
    let stderrBytes = 0
    const timer = setTimeout(() => {
      child.kill('SIGTERM')
      reject(new Error(`The packaged cursor helper timed out while running ${command.command}.`))
    }, timeoutMs)
    child.stdout.on('data', (chunk) => { stdout += String(chunk) })
    child.stderr.on('data', (chunk) => { stderrBytes += Buffer.byteLength(chunk) })
    child.once('error', reject)
    child.once('close', () => {
      clearTimeout(timer)
      let response
      try { response = JSON.parse(stdout.trim()) } catch {
        reject(new Error(`The packaged cursor helper returned invalid JSON (${stderrBytes} diagnostic bytes).`))
        return
      }
      if (response?.version !== 1 || response?.id !== id) {
        reject(new Error('The packaged cursor helper returned an unverifiable response.'))
        return
      }
      if (response.ok !== true) {
        const details = response?.error?.details ? ` ${JSON.stringify(response.error.details)}` : ''
        const error = new Error(`${command.command}: ${response?.error?.message || 'the packaged cursor helper rejected the action.'}${details}`)
        error.code = response?.error?.code
        reject(error)
        return
      }
      resolve(response.result)
    })
    child.stdin.end(`${request}\n`, 'utf8')
  })
}

function distance(left, right) {
  return Math.hypot(left.x - right.x, left.y - right.y)
}

async function waitForFile(filePath, expected) {
  const deadline = Date.now() + 10_000
  let actual = ''
  while (Date.now() < deadline) {
    actual = await readFile(filePath, 'utf8').catch(() => '')
    if (actual === expected) return
    await wait(100)
  }
  throw new Error(`TextEdit did not save the exact Unicode text generated by the cursor helper (expected ${expected.length} characters; saved ${actual.length}).`)
}

async function waitForApplicationWindow(bundleIdentifier) {
  const deadline = Date.now() + 10_000
  while (Date.now() < deadline) {
    const focused = await helper({ command: 'focus-application', bundleIdentifier }).catch(() => null)
    if (focused?.observation?.frontmostApplication?.bundleIdentifier === bundleIdentifier && focused.observation.frontmostWindow) {
      return focused.observation
    }
    await wait(250)
  }
  throw new Error(`The ${bundleIdentifier} audit window did not become available.`)
}

const temporaryDirectory = await mkdtemp(path.join(os.tmpdir(), 'omnicode-cursor-audit-'))
const textFile = path.join(temporaryDirectory, 'OmniCode Cursor Audit.txt')
const secureFieldFile = path.join(temporaryDirectory, 'OmniCode Secure Field Audit.html')
const initialText = 'Temporary OmniCode Cursor audit document.\n'
const expectedText = `OmniCode Cursor Mode live test ${randomUUID()} — Unicode ✓\n`
let originalObservation
let textEditOpened = false
let secureFieldOpened = false
let unallowlistedInputBoundary = 'not-run-original-app-was-allowlisted'
let secureFieldBoundary = 'not-run'

try {
  await writeFile(textFile, initialText, { encoding: 'utf8', mode: 0o600 })
  originalObservation = await helper({ command: 'observe' })
  const originalBundleIdentifier = originalObservation.frontmostApplication?.bundleIdentifier
  if (!originalBundleIdentifier || !interactiveBundleIdentifiers.has(originalBundleIdentifier)) {
    try {
      await helper({ command: 'press-key', key: 'a', modifiers: [], repeat: 1 })
      throw new Error('The cursor helper posted keyboard input to an unallowlisted application.')
    } catch (error) {
      if (error?.code !== 'invalid-request' || !/outside its allowlist/u.test(error.message)) throw error
      unallowlistedInputBoundary = 'verified'
    }
  }

  const originalCursor = originalObservation.cursor
  const destination = {
    x: originalCursor.x > 50 ? originalCursor.x - 24 : originalCursor.x + 24,
    y: originalCursor.y
  }
  await helper({ command: 'move', x: destination.x, y: destination.y, durationMs: 120 })
  const movedObservation = await helper({ command: 'observe' })
  if (distance(movedObservation.cursor, destination) > 3) {
    throw new Error('The cursor helper did not move the pointer to the requested location.')
  }
  await helper({ command: 'move', x: originalCursor.x, y: originalCursor.y, durationMs: 120 })
  const restoredObservation = await helper({ command: 'observe' })
  if (distance(restoredObservation.cursor, originalCursor) > 3) {
    throw new Error('The cursor helper did not restore the pointer location.')
  }

  await runProcess('/usr/bin/open', ['-a', 'TextEdit', textFile])
  textEditOpened = true
  await wait(750)
  const focused = await helper({ command: 'focus-application', bundleIdentifier: 'com.apple.TextEdit' })
  if (focused?.observation?.frontmostApplication?.bundleIdentifier !== 'com.apple.TextEdit') {
    throw new Error('TextEdit did not become the frontmost application.')
  }
  const windowFrame = focused?.observation?.frontmostWindow
  if (!windowFrame || windowFrame.width < 160 || windowFrame.height < 160) {
    throw new Error('The cursor helper could not identify a usable TextEdit window.')
  }

  const editorPoint = {
    x: windowFrame.x + Math.min(windowFrame.width - 40, Math.max(80, windowFrame.width / 2)),
    y: windowFrame.y + Math.min(windowFrame.height - 40, Math.max(120, windowFrame.height / 2))
  }
  await helper({ command: 'move', x: editorPoint.x, y: editorPoint.y, durationMs: 120 })
  await helper({ command: 'click', button: 'left', count: 1 })
  await wait(150)
  await helper({ command: 'click', button: 'left', count: 2 })
  await wait(150)

  await helper({ command: 'press-key', key: 'a', modifiers: ['command'], repeat: 1 })
  await helper({ command: 'type-text', text: expectedText })
  await helper({ command: 'press-key', key: 's', modifiers: ['command'], repeat: 1 })
  await waitForFile(textFile, expectedText)

  await helper({ command: 'scroll', deltaX: 0, deltaY: 120 })
  await helper({ command: 'press-key', key: 'w', modifiers: ['command'], repeat: 1 })
  textEditOpened = false

  await writeFile(secureFieldFile, [
    '<!doctype html><meta charset="utf-8"><title>OmniCode Secure Field Audit</title>',
    '<style>html,body{margin:0;height:100%}input{position:fixed;inset:0;width:100%;height:100%;box-sizing:border-box;font-size:24px}</style>',
    '<input type="password" autofocus aria-label="Secure audit field">'
  ].join(''), { encoding: 'utf8', mode: 0o600 })
  await runProcess('/usr/bin/open', ['-a', 'Safari', secureFieldFile])
  secureFieldOpened = true
  const safari = await waitForApplicationWindow('com.apple.Safari')
  const securePoint = {
    x: safari.frontmostWindow.x + safari.frontmostWindow.width / 2,
    y: safari.frontmostWindow.y + safari.frontmostWindow.height / 2
  }
  await helper({ command: 'move', x: securePoint.x, y: securePoint.y, durationMs: 120 })
  await helper({ command: 'click', button: 'left', count: 1 })
  await wait(250)
  try {
    await helper({ command: 'type-text', text: 'SAFE-AUDIT-MARKER' })
    throw new Error('The cursor helper accepted text for a secure password field.')
  } catch (error) {
    if (error?.code !== 'invalid-request' || !/secure or password field/u.test(error.message)) throw error
    secureFieldBoundary = 'verified'
  }
  await helper({ command: 'press-key', key: 'w', modifiers: ['command'], repeat: 1 })
  secureFieldOpened = false

  console.log(JSON.stringify({
    liveCursorAudit: 'passed',
    pointerMove: 'verified-and-restored',
    pointerClick: 'verified-by-editor-focus',
    pointerDoubleClick: 'native-command-succeeded',
    focusApplication: 'verified',
    unicodeTyping: 'verified-on-disk',
    keyboardShortcut: 'verified-by-save',
    scroll: 'native-command-succeeded',
    unallowlistedInputBoundary,
    secureFieldBoundary,
    temporaryFilePersisted: false
  }, null, 2))
} finally {
  if (secureFieldOpened) {
    await helper({ command: 'press-key', key: 'w', modifiers: ['command'], repeat: 1 }).catch(() => undefined)
  }
  if (textEditOpened) {
    await helper({ command: 'press-key', key: 'w', modifiers: ['command'], repeat: 1 }).catch(() => undefined)
  }
  if (originalObservation?.frontmostApplication?.bundleIdentifier) {
    const bundleIdentifier = originalObservation.frontmostApplication.bundleIdentifier
    await helper({
      command: 'focus-application',
      bundleIdentifier
    }).catch(async () => {
      if (/^[A-Za-z0-9.-]{1,256}$/u.test(bundleIdentifier)) {
        await runProcess('/usr/bin/open', ['-b', bundleIdentifier]).catch(() => undefined)
      }
    })
  }
  if (originalObservation?.cursor) {
    await helper({
      command: 'move',
      x: originalObservation.cursor.x,
      y: originalObservation.cursor.y,
      durationMs: 0
    }).catch(() => undefined)
  }
  await rm(temporaryDirectory, { recursive: true, force: true })
}
